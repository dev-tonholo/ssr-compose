#!/usr/bin/env python3
"""List every agent file in a repo's agent folders and whether sync-agents generated it.

Usage: python3 find-agents.py <repo> [--hand-made] [--snapshot <dir>]
  --hand-made        print only files sync-agents did not write
  --snapshot <dir>   copy each hand-made file to <dir>/<same relative path> (relative to the repo)
Looks one folder deep too (for example .agents/agents/<role>/agent.md).
Output: "<relative path><TAB>generated|hand-made" per file, sorted. Folders that are symlinks are skipped.
Exit codes: 0 ok, 2 bad arguments or the repo cannot be opened.
"""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

AGENT_FOLDERS = (".ai/agents", ".claude/agents", ".agents/agents", ".codex/agents", ".opencode/agents", ".github/agents")
AGENT_PATTERNS = ("*.md", "*.toml", "*/*.md", "*/*.toml")
MARKER_PREFIXES = ("# generated by sync-agents.py from .ai/agents/", "# generated by sync-agents.sh from .ai/agents/")
MARKER_LINES = 2


def kind_of(path: Path) -> str:
    head = path.read_text(errors="replace").splitlines()[:MARKER_LINES]
    return "generated" if any(prefix in line for line in head for prefix in MARKER_PREFIXES) else "hand-made"


def agent_files() -> list[tuple[str, str]]:
    files = []
    for folder in map(Path, AGENT_FOLDERS):
        if not folder.is_dir() or folder.is_symlink():
            continue
        files += [(str(path), kind_of(path)) for pattern in AGENT_PATTERNS for path in folder.glob(pattern) if path.is_file() and not path.name.startswith(".")]
    return sorted(files)


def parse_arguments(arguments: list[str]) -> tuple[Path, bool, str] | str:
    if not arguments:
        return "usage: find-agents.py <repo> [--hand-made] [--snapshot <dir>]"
    repo, rest = Path(arguments[0]), arguments[1:]
    hand_made_only, snapshot = False, ""
    while rest:
        option = rest.pop(0)
        if option == "--hand-made":
            hand_made_only = True
        elif option == "--snapshot" and rest:
            snapshot = rest.pop(0)
        else:
            return f"Unknown option '{option}'"
    return repo, hand_made_only, snapshot


def main(arguments: list[str]) -> int:
    parsed = parse_arguments(arguments)
    if isinstance(parsed, str):
        print(parsed)
        return 2
    repo, hand_made_only, snapshot = parsed
    if not repo.is_dir():
        print(f"Cannot open repo '{repo}'")
        return 2
    os.chdir(repo)
    for path, kind in agent_files():
        if hand_made_only and kind == "generated":
            continue
        print(f"{path}\t{kind}")
        if snapshot and kind == "hand-made":
            target = Path(snapshot) / path
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
