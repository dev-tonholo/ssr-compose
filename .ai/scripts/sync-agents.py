#!/usr/bin/env python3
"""Write each tool's agent copies from .ai/agents/*.md, using the model map in .ai/agents.json.

Usage: python3 .ai/scripts/sync-agents.py [repo-path] [--check]
  repo-path  default: two folders above this script (the repo root when it sits in .ai/scripts/)
  --check    write nothing; exit 1 when a copy is missing, out of date or has no source,
             or when an output folder holds a file this script did not write
Exit codes: 0 ok, 1 problems found, 2 bad arguments or the repo cannot be opened.
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

SOURCE_DIR = Path(".ai/agents")
MODEL_MAP = Path(".ai/agents.json")
MARKER_PREFIX = "# generated by sync-agents.py from"
OLD_MARKER_PREFIX = "# generated by sync-agents.sh from"
TOML_LITERAL_QUOTES = "'''"
CLAUDE_EDIT_TOOLS = "Write, Edit, NotebookEdit"
ANTIGRAVITY_READ_TOOLS = ("run_command", "view_file", "find_by_name", "grep_search", "list_dir", "read_url_content", "search_web")
ANTIGRAVITY_EDIT_TOOLS = ("replace_file_content", "write_to_file")
OUTPUT_DIRS = {"claude": ".claude/agents", "codex": ".codex/agents", "antigravity": ".agents/agents", "opencode": ".opencode/agents"}
TIER_FALLBACK = {"max": "top"}
ADVISOR = "advisor"
READ_ONLY = "read-only"
CHECK_OPTION = "--check"


def visible_files(folder: Path, pattern: str) -> list[Path]:
    return sorted(path for path in folder.glob(pattern) if not path.name.startswith(".") and path.is_file())


class Agent:
    def __init__(self, path: Path) -> None:
        self.path = path
        self.name = path.stem
        self.text = path.read_text(errors="replace")

    def value(self, key: str) -> str:
        lines = self.text.splitlines()
        if not lines or lines[0] != "---":
            return ""
        for line in lines[1:]:
            if line == "---":
                break
            if line.startswith(f"{key}:"):
                return line[len(key) + 1:].lstrip(" ")
        return ""

    def body(self) -> str:
        lines = self.text.splitlines()
        closing = next((index for index, line in enumerate(lines) if index > 0 and line == "---"), len(lines))
        body = lines[closing + 1:]
        while body and body[0] == "":
            body.pop(0)
        return "\n".join(body).rstrip("\n").replace("../", ".ai/")

    def dispatchable(self) -> bool:
        return self.value("dispatchable") != "false"


def quoted(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def marker(name: str) -> str:
    return f"{MARKER_PREFIX} {SOURCE_DIR}/{name}.md"


def is_generated(path: Path) -> bool:
    if not path.is_file():
        return False
    lines = path.read_text(errors="replace").splitlines()
    index = 0 if path.suffix == ".toml" else 1
    line = lines[index] if len(lines) > index else ""
    return line.startswith((MARKER_PREFIX, OLD_MARKER_PREFIX))


class Renderer:
    def __init__(self, models: dict) -> None:
        self.models = models

    def model(self, tool: str, agent: Agent) -> str:
        """Return the tool's model for the agent's tier; a tier with no entry falls back to the one below it, if any."""
        models = self.models.get(tool) or {}
        tier = agent.value("tier")
        return models.get(tier) or models.get(TIER_FALLBACK.get(tier, ""), "") or ""

    def yaml_model(self, tool: str, agent: Agent) -> list[str]:
        model = self.model(tool, agent)
        return [f"model: {quoted(model)}"] if model else []

    def markdown(self, header: list[str], agent: Agent) -> str:
        return "\n".join(["---", marker(agent.name), *header, "---", "", agent.body()])

    def claude(self, agent: Agent) -> str:
        denied = CLAUDE_EDIT_TOOLS if agent.value("access") == READ_ONLY else ""
        if agent.name == ADVISOR:
            denied = f"{denied}, Agent" if denied else "Agent"
        header = [f"name: {quoted(agent.name)}", f"description: {quoted(agent.value('description'))}"]
        header += self.yaml_model("claude", agent)
        header.append(f"effort: {quoted(agent.value('effort'))}")
        header += [f"disallowedTools: {quoted(denied)}"] if denied else []
        return self.markdown(header, agent)

    def codex(self, agent: Agent) -> str:
        model = self.model("codex", agent)
        lines = [marker(agent.name), f"name = {quoted(agent.name)}", f"description = {quoted(agent.value('description'))}"]
        lines += [f"model = {quoted(model)}"] if model else []
        lines.append(f"model_reasoning_effort = {quoted(agent.value('effort'))}")
        lines += [f"developer_instructions = {TOML_LITERAL_QUOTES}", agent.body(), TOML_LITERAL_QUOTES]
        return "\n".join(lines)

    def antigravity(self, agent: Agent) -> str:
        tools = ANTIGRAVITY_READ_TOOLS + (ANTIGRAVITY_EDIT_TOOLS if agent.value("access") == "write" else ())
        header = [f"name: {quoted(agent.name)}", f"description: {quoted(agent.value('description'))}"]
        header += self.yaml_model("antigravity", agent)
        header += ["mainAgent: false", "subagent: true", "tools:"] + [f"  - {tool}" for tool in tools]
        return self.markdown(header, agent)

    def opencode(self, agent: Agent) -> str:
        header = [f"description: {quoted(agent.value('description'))}", "mode: subagent"]
        header += self.yaml_model("opencode", agent)
        if agent.value("access") == READ_ONLY:
            header += ["permissions:", '  - action: "edit"', '    resource: "*"', '    effect: "deny"']
        return self.markdown(header, agent)


class Sync:
    def __init__(self, renderer: Renderer, check_only: bool) -> None:
        self.renderer = renderer
        self.check_only = check_only
        self.problems = 0

    def problem(self, message: str) -> None:
        print(message)
        self.problems += 1

    def write_copy(self, tool: str, agent: Agent, target: Path) -> None:
        if tool == "codex" and TOML_LITERAL_QUOTES in agent.text:
            self.problem(f"{agent.path} contains {TOML_LITERAL_QUOTES} and cannot be written as a TOML literal string")
            return
        rendered = getattr(self.renderer, tool)(agent).rstrip("\n")
        if self.check_only:
            current = target.read_text(errors="replace").rstrip("\n") if target.is_file() else None
            if current != rendered:
                self.problem(f"out of date: {target}")
            return
        try:
            target.write_text(rendered + "\n")
        except OSError:
            self.problem(f"cannot write {target}")

    def refuse_foreign_files(self, folder: Path, extension: str) -> bool:
        candidates = visible_files(folder, f"*.{extension}") + visible_files(folder, f"*/*.{extension}")
        foreign = [path for path in candidates if not is_generated(path)]
        for path in foreign:
            self.problem(f"not generated, refusing to touch: {path}")
        return bool(foreign)

    def remove_orphans(self, folder: Path, extension: str) -> None:
        for path in visible_files(folder, f"*.{extension}"):
            if not is_generated(path):
                continue
            source = SOURCE_DIR / f"{path.stem}.md"
            if source.is_file() and Agent(source).dispatchable():
                continue
            if self.check_only:
                self.problem(f"no source agent: {path}")
            else:
                path.unlink()

    def sync_tool(self, tool: str, agents: list[Agent]) -> None:
        folder = Path(OUTPUT_DIRS[tool])
        if folder.is_symlink():
            self.problem(f"{folder} is a symlink; remove the link (rm {folder}), then sync")
            return
        extension = "toml" if tool == "codex" else "md"
        if self.refuse_foreign_files(folder, extension):
            return
        if not self.check_only:
            folder.mkdir(parents=True, exist_ok=True)
        for agent in agents:
            self.write_copy(tool, agent, folder / f"{agent.name}.{extension}")
        self.remove_orphans(folder, extension)


def parse_arguments(arguments: list[str]) -> tuple[Path, bool] | str:
    repo = Path(os.path.abspath(__file__)).parent.parent.parent
    check_only = False
    for argument in arguments:
        if argument == CHECK_OPTION:
            check_only = True
        elif argument.startswith("--"):
            return f"Unknown option '{argument}'"
        else:
            repo = Path(argument)
    return repo, check_only


def load_map() -> dict | None:
    try:
        loaded = json.loads(MODEL_MAP.read_text())
    except ValueError:
        loaded = None
    if not isinstance(loaded, dict):
        print(f"invalid {MODEL_MAP}")
        return None
    return loaded


def main(arguments: list[str]) -> int:
    parsed = parse_arguments(arguments)
    if isinstance(parsed, str):
        print(parsed)
        return 2
    repo, check_only = parsed
    if not repo.is_dir():
        print(f"Cannot open {repo}")
        return 2
    os.chdir(repo)
    if not MODEL_MAP.is_file():
        print(f"missing {MODEL_MAP}")
        return 1
    model_map = load_map()
    if model_map is None:
        return 1
    agents = [Agent(path) for path in visible_files(SOURCE_DIR, "*.md")]
    sync = Sync(Renderer(model_map.get("models") or {}), check_only)
    for tool in model_map.get("tools") or []:
        if tool in OUTPUT_DIRS:
            sync.sync_tool(tool, [agent for agent in agents if agent.dispatchable()])
        else:
            sync.problem(f"unknown tool '{tool}' in {MODEL_MAP}")
    if sync.problems:
        print("Run: python3 .ai/scripts/sync-agents.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
